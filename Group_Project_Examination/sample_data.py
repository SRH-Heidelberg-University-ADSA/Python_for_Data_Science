"""sample_data.py - fake data for the Habit Tracker project.

Provided by the instructor. Please do not edit this file.

Two ways to use it:
    make_test_data()   -> (data, answers)   small data set with KNOWN correct answers
                                            (for unit tests and for check_contract.py)
    make_demo_data()   -> data              bigger random data set (10 habits, 60 days) for demos
                                            and screenshots (Role E: menu option 9)
                                            All names are unique. To test two habits with the
                                            same name, create them yourself with add_habit.

Run `python sample_data.py` to write a demo file called demo_data.json.

For INTEGRATION tests (test_integration_X.py) you do not need this file:
build your data with the contract functions (add_habit, mark_done, ...).
"""
import json
import random
from datetime import date, timedelta


def _day(today, days_ago):
    """Return a date as text, for example '2026-10-05'."""
    return (today - timedelta(days=days_ago)).isoformat()


def make_test_data(today=None):
    """Return (data, answers).

    The dates are always relative to today, so the answers stay correct
    every day. Day 0 = today, 1 = yesterday, and so on.
    """
    today = today or date.today()

    # habit id -> (name, list of "days ago" when it was done)
    plan = {
        "1": ("Read", list(range(0, 5))),                        # done the last 5 days
        "2": ("Exercise", [1, 2, 3] + list(range(10, 17))),      # streak ended yesterday
        "3": ("Meditate", [3, 4, 8]),                            # streak is broken
        "4": ("Journal", []),                                    # never done
        "5": ("Drink water", list(range(0, 30))),                # done every day
    }

    rng = random.Random(42)  # fixed seed: same order for everybody
    data = {"habits": {}, "log": {}}
    for habit_id, (name, days_ago_list) in plan.items():
        data["habits"][habit_id] = {"name": name, "created": _day(today, 40)}
        dates = [_day(today, d) for d in days_ago_list]
        rng.shuffle(dates)  # the log is NOT sorted, on purpose
        if dates:  # habit 4 has no log entry at all, on purpose
            data["log"][habit_id] = dates

    answers = {
        "current_streak": {"1": 5, "2": 3, "3": 0, "4": 0, "5": 30},
        "longest_streak": {"1": 5, "2": 7, "3": 2, "4": 0, "5": 30},
        # (habit id, days, expected rate). The window is the last `days` calendar
        # days, today included. The last five lines are edge cases: a window of
        # 1 day, a very short window, and windows longer than the data.
        "completion_rate": [
            ("1", 10, 0.5),
            ("2", 14, 0.5),
            ("3", 10, 0.3),
            ("4", 10, 0.0),
            ("5", 7, 1.0),
            ("1", 1, 1.0),    # done today
            ("2", 1, 0.0),    # not done today
            ("1", 3, 1.0),    # done on each of the last 3 days
            ("5", 60, 0.5),   # 30 done days in a 60-day window
            ("2", 30, 0.33),  # 10 of 30 days
        ],
        "weekly_summary": {"1": 5, "2": 3, "3": 2, "4": 0, "5": 7},
    }
    return data, answers


def make_demo_data(n_habits=10, days=60, seed=1):
    """Return a bigger random data set. Same seed = same data."""
    names = ["Read", "Exercise", "Meditate", "Journal", "Drink water",
             "Study Python", "Walk 10k steps", "Sleep before 11pm"]
    rng = random.Random(seed)
    today = date.today()
    data = {"habits": {}, "log": {}}
    for i in range(1, n_habits + 1):
        habit_id = str(i)
        name = names[(i - 1) % len(names)]
        if i > len(names):  # from the 9th habit on, keep every name unique
            name = name + " " + str(i)
        data["habits"][habit_id] = {"name": name, "created": _day(today, days)}
        chance = rng.uniform(0.3, 0.9)  # how reliable this "user" is
        done = [_day(today, d) for d in range(days) if rng.random() < chance]
        if done:
            data["log"][habit_id] = done
    return data


if __name__ == "__main__":
    with open("demo_data.json", "w", encoding="utf-8") as file:
        json.dump(make_demo_data(), file, indent=2)
    print("Wrote demo_data.json")